#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
import json
import os
import pathlib
import re
import shlex
from datetime import datetime, timezone
from typing import Any


ARTIFACT_PATH_RE = re.compile(
    r"(?i)(?:^|/)(?:"
    r".*\.sarif|"
    r"(?:sbom|bom|cyclonedx|spdx|provenance|attestation|in-toto|audit-report|security-report|incident-bundle|evidence-bundle|forensics-bundle|scan-summary|release-summary)[^/]*\.(?:json|md|txt|yaml|yml)"
    r")$"
)
TEXT_SURFACE_RE = re.compile(r"(?i)\.(?:sarif|json|md|txt|yaml|yml)$")
SARIF_SUPPRESS_RE = re.compile(
    r'(?i)(?:"suppressions"\s*:|\"baselineState\"\s*:\s*\"absent\"|\"level\"\s*:\s*\"none\"|\"kind\"\s*:\s*\"pass\")'
)
SBOM_SOURCE_SWAP_RE = re.compile(
    r"(?i)(?:raw\.githubusercontent\.com|pastebin\.com|gist\.githubusercontent\.com|file://|git\+https?://|downloadUrl|externalRefs?)[^\n\r]{0,140}"
)
PROVENANCE_MISMATCH_RE = re.compile(
    r"(?i)(?:\"builder(?:\.id)?\"\s*:\s*\"(?:unknown|manual|file://|https?://raw|https?://gist)|\"predicateType\"\s*:\s*\"(?:unknown|manual)\"|\"sha256\"\s*:\s*\"(?:0{12,}|tbd|unknown)\")"
)
SECRET_MARKER_RE = re.compile(
    r"(?i)(?:gh[pousr]_[A-Za-z0-9_]{20,}|github_pat_[A-Za-z0-9_]{20,}|AKIA[0-9A-Z]{16}|ASIA[0-9A-Z]{16}|-----BEGIN [A-Z ]+PRIVATE KEY-----|(?:api[_-]?key|token|secret|password)\s*[:=]\s*[A-Za-z0-9._/+\\=-]{12,})"
)
INCIDENT_POISON_RE = re.compile(
    r"(?i)(?:ignore prior findings|treat incident as benign|open external bundle|download evidence from|do not preserve evidence)"
)
SUMMARY_FALSE_RE = re.compile(
    r'(?is)(?:no findings|all clear|fully clean|zero issues).{0,220}(?:critical|high|error|fail(?:ed|ure)|severity)'
)
CHECKSUM_DRIFT_RE = re.compile(
    r'(?i)(?:\"sha256\"\s*:\s*\"(?:0{12,}|tbd|unknown)\"|\"checksum\"\s*:\s*\"(?:tbd|unknown)\"|md5\s*[:=]\s*[0-9a-f]{32})'
)
REPORT_COVERUP_RE = re.compile(
    r"(?i)(?:waive all|suppress all|mark as false positive without review|do not report|hide this finding|remove the evidence section)"
)
REGEN_MISMATCH_RE = re.compile(
    r"(?i)(?:manually edited generated file|do not regenerate|generator disabled|generated by unknown|rendered without scanner)"
)
EVIDENCE_POINTER_REWRITE_RE = re.compile(
    r"(?i)(?:evidence|bundle|sarif|sbom|provenance|report)[^\n\r]{0,120}(?:raw\.githubusercontent\.com|pastebin\.com|gist\.githubusercontent\.com|file://|/tmp/|/private/tmp/|Downloads/)"
)


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def state_dir(root: pathlib.Path) -> pathlib.Path:
    home = os.environ.get("STALLION_HOME") or os.environ.get("STALLION_HOME")
    if home:
        return pathlib.Path(home) / "state"
    return pathlib.Path(os.path.expanduser("~")) / ".stallion" / "state"


def artifact_store_path(root: pathlib.Path) -> pathlib.Path:
    return state_dir(root) / "artifacts.json"


def load_store(root: pathlib.Path) -> dict[str, Any]:
    path = artifact_store_path(root)
    if not path.exists():
        return {"version": 1, "artifacts": {}}
    try:
        payload = json.loads(path.read_text())
    except json.JSONDecodeError:
        return {"version": 1, "artifacts": {}}
    if not isinstance(payload, dict):
        return {"version": 1, "artifacts": {}}
    payload.setdefault("version", 1)
    payload.setdefault("artifacts", {})
    return payload


def save_store(root: pathlib.Path, store: dict[str, Any]) -> None:
    path = artifact_store_path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(store, indent=2, sort_keys=True) + "\n")


def _shell_split(command: str) -> list[str]:
    try:
        return shlex.split(command, posix=os.name != "nt")
    except ValueError:
        return [token for token in command.strip().split() if token]


def _normalize_path_token(token: str) -> pathlib.Path:
    stripped = token.strip("'\"= ")
    expanded = os.path.expanduser(stripped)
    path = pathlib.Path(expanded)
    if not path.is_absolute():
        path = pathlib.Path(os.path.abspath(str(pathlib.Path.cwd() / path)))
    return path


def _fileop_surface(matcher: str, payload: str) -> tuple[pathlib.Path | None, str]:
    tokens = _shell_split(payload)
    if not tokens:
        return None, ""
    first = tokens[0]
    path = _normalize_path_token(first)
    if matcher in {"Write", "Edit", "MultiEdit"}:
        return path, payload[len(first) :].strip()
    return path, ""


def _fingerprint(text: str) -> str:
    return hashlib.sha256(re.sub(r"\s+", " ", text.strip()).encode("utf-8")).hexdigest()


def _surface_from_path(path: pathlib.Path) -> str:
    name = path.name.lower()
    if name.endswith(".sarif"):
        return "sarif-report"
    if "sbom" in name or "cyclonedx" in name or "spdx" in name or "bom" in name:
        return "sbom-report"
    if "provenance" in name or "attestation" in name or "in-toto" in name:
        return "provenance-report"
    if "incident" in name or "evidence" in name or "forensics" in name:
        return "incident-bundle"
    if "audit" in name or "security" in name:
        return "security-report"
    return "artifact-report"


def _hit(module: str, decision: str, identity: dict[str, Any], reason: str, safer: str) -> dict[str, Any]:
    return {
        "module": module,
        "name": module.replace("-", " ").title(),
        "category": "artifact-trust",
        "family": "Review, Artifacts & Evidence",
        "decision": decision,
        "exit_code": 2 if decision == "block" else 0,
        "output": reason,
        "metadata": {
            "reason": reason,
            "confidence": 0.96 if decision == "block" else 0.84,
            "safer_alternative": safer,
            "artifact_identity": identity,
        },
    }


def infer_artifact_identity(matcher: str, payload: str) -> tuple[pathlib.Path | None, str, dict[str, Any] | None]:
    if matcher not in {"Read", "Write", "Edit", "MultiEdit"}:
        return None, "", None
    path, content = _fileop_surface(matcher, payload)
    if path is None:
        return None, "", None
    location = str(path).replace("\\", "/")
    if not ARTIFACT_PATH_RE.search(location):
        return path, content, None
    if path.suffix and not TEXT_SURFACE_RE.search(path.name):
        return path, content, None
    identity = {
        "path": str(path),
        "surface": _surface_from_path(path),
        "fingerprint": _fingerprint(content) if content else None,
        "matcher": matcher,
    }
    return path, content, identity


def assess_fileop(root: pathlib.Path, event: str, matcher: str, payload: str, context: dict[str, Any] | None = None) -> dict[str, Any]:
    _ = context
    if event != "PreToolUse":
        return {"identity": None, "hit": None}
    path, content, identity = infer_artifact_identity(matcher, payload)
    if identity is None or path is None:
        return {"identity": None, "hit": None}
    store = load_store(root)
    record = store.setdefault("artifacts", {}).get(str(path))
    fingerprint = identity.get("fingerprint")
    hit = None
    trust_state = record.get("trust_state") if isinstance(record, dict) else "observed"

    if isinstance(record, dict) and record.get("trust_state") == "quarantined":
        hit = _hit(
            "artifact-quarantine-bypass-guard",
            "block",
            identity,
            f"Blocked access to quarantined report or artifact surface {path}.",
            f"Review the artifact first and move it out of quarantine with `./bin/stallion artifacts trust {path}` only if it is actually safe.",
        )
        trust_state = "quarantined"
    elif matcher in {"Write", "Edit", "MultiEdit"} and isinstance(record, dict) and record.get("trust_state") == "trusted" and fingerprint and record.get("fingerprint") and record.get("fingerprint") != fingerprint:
        hit = _hit(
            "artifact-drift-guard",
            "prompt",
            identity,
            f"Review required because trusted artifact surface {path} changed.",
            f"Run `./bin/stallion artifacts diff {path}` and then `./bin/stallion artifacts trust {path}` if the regenerated report is expected.",
        )
        trust_state = "drifted"
    elif matcher in {"Write", "Edit", "MultiEdit"} and not isinstance(record, dict):
        hit = _hit(
            "artifact-source-review-guard",
            "prompt",
            identity,
            f"Review required before new artifact surface {path} becomes trusted.",
            f"Run `./bin/stallion artifacts trust {path}` only after confirming this generated report or evidence bundle is expected.",
        )
        trust_state = "observed"

    if matcher in {"Write", "Edit", "MultiEdit"}:
        if SARIF_SUPPRESS_RE.search(content):
            hit = _hit(
                "sarif-finding-suppression-guard",
                "block",
                identity,
                f"Blocked SARIF suppression or silent pass markers in {path}.",
                "Do not suppress, zero out, or silently pass findings inside trusted SARIF output.",
            )
            trust_state = "quarantined"
        elif SBOM_SOURCE_SWAP_RE.search(content):
            hit = _hit(
                "sbom-source-swap-guard",
                "prompt",
                identity,
                f"Review required because SBOM or dependency-report sources drifted to external or raw locations in {path}.",
                "Keep SBOM materials and external references pinned to reviewed package sources and local generation inputs.",
            )
            trust_state = "drifted"
        elif PROVENANCE_MISMATCH_RE.search(content):
            hit = _hit(
                "provenance-mismatch-guard",
                "block",
                identity,
                f"Blocked untrusted provenance or attestation metadata in {path}.",
                "Keep provenance builders, predicate types, and digests concrete and reviewable instead of unknown or raw placeholders.",
            )
            trust_state = "quarantined"
        elif SECRET_MARKER_RE.search(content):
            hit = _hit(
                "audit-report-secret-redaction-bypass-guard",
                "block",
                identity,
                f"Blocked unredacted secret material inside trusted report surface {path}.",
                "Reports and bundles should contain masked evidence, not live tokens, credentials, or private-key bodies.",
            )
            trust_state = "quarantined"
        elif INCIDENT_POISON_RE.search(content):
            hit = _hit(
                "incident-bundle-poison-guard",
                "block",
                identity,
                f"Blocked poisoned incident or evidence guidance in {path}.",
                "Incident bundles should preserve evidence and local review context, not redirect operators to external mutable content or weaken response.",
            )
            trust_state = "quarantined"
        elif SUMMARY_FALSE_RE.search(content):
            hit = _hit(
                "summary-falsification-guard",
                "block",
                identity,
                f"Blocked inconsistent 'all clear' summary language in {path}.",
                "Summaries should not claim zero findings when the same report still references critical or failing conditions.",
            )
            trust_state = "quarantined"
        elif CHECKSUM_DRIFT_RE.search(content):
            hit = _hit(
                "checksum-report-drift-guard",
                "prompt",
                identity,
                f"Review required because checksum or digest fields in {path} look placeholder-like or drifted.",
                "Keep report digests concrete and regenerated from the real artifact set instead of placeholders or conflicting checksum schemes.",
            )
            trust_state = "drifted"
        elif REPORT_COVERUP_RE.search(content):
            hit = _hit(
                "security-report-coverup-guard",
                "block",
                identity,
                f"Blocked report-coverup language in {path}.",
                "Do not suppress, waive, or hide findings inside trusted reports unless the review trail exists somewhere explicit and reviewed.",
            )
            trust_state = "quarantined"
        elif REGEN_MISMATCH_RE.search(content):
            hit = _hit(
                "artifact-regeneration-mismatch-guard",
                "prompt",
                identity,
                f"Review required because {path} claims to be generated but carries manual-or-unknown generation markers.",
                "Regenerate trusted reports through the reviewed pipeline instead of hand-editing generated evidence files.",
            )
            trust_state = "drifted"
        elif EVIDENCE_POINTER_REWRITE_RE.search(content):
            hit = _hit(
                "evidence-pointer-rewrite-guard",
                "block",
                identity,
                f"Blocked evidence-pointer rewrite in {path}.",
                "Keep evidence pointers local, stable, and reviewable instead of redirecting incident material to raw, temp, or mutable external locations.",
            )
            trust_state = "quarantined"

    updated = {
        "path": str(path),
        "surface": identity["surface"],
        "fingerprint": fingerprint or (record or {}).get("fingerprint"),
        "trust_state": trust_state,
        "first_seen_at": (record or {}).get("first_seen_at", utc_now()) if isinstance(record, dict) else utc_now(),
        "last_seen_at": utc_now(),
        "last_reason": hit["module"] if hit else (record or {}).get("last_reason") if isinstance(record, dict) else None,
        "last_drift": utc_now() if hit and hit["module"] == "artifact-drift-guard" else (record or {}).get("last_drift") if isinstance(record, dict) else None,
    }
    store.setdefault("artifacts", {})[str(path)] = updated
    save_store(root, store)
    return {"identity": identity, "hit": hit}


def list_artifacts(root: pathlib.Path) -> list[dict[str, Any]]:
    items = [dict(item) for item in load_store(root).get("artifacts", {}).values() if isinstance(item, dict)]
    items.sort(key=lambda item: item.get("path", ""))
    return items


def set_trust(root: pathlib.Path, selector: str, state: str) -> bool:
    store = load_store(root)
    record = store.setdefault("artifacts", {}).get(selector)
    if not isinstance(record, dict):
        return False
    record["trust_state"] = state
    record["last_seen_at"] = utc_now()
    save_store(root, store)
    return True


def forget_artifact(root: pathlib.Path, selector: str) -> bool:
    store = load_store(root)
    if selector in store.setdefault("artifacts", {}):
        store["artifacts"].pop(selector, None)
        save_store(root, store)
        return True
    return False


def diff_artifact(root: pathlib.Path, selector: str) -> dict[str, Any] | None:
    record = load_store(root).get("artifacts", {}).get(selector)
    if isinstance(record, dict):
        return record
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description="Manage Stallion artifact trust")
    parser.add_argument("--root", required=True)
    subparsers = parser.add_subparsers(dest="command", required=True)
    list_parser = subparsers.add_parser("list")
    list_parser.add_argument("--json", action="store_true")
    trust_parser = subparsers.add_parser("trust")
    trust_parser.add_argument("selector")
    quarantine_parser = subparsers.add_parser("quarantine")
    quarantine_parser.add_argument("selector")
    forget_parser = subparsers.add_parser("forget")
    forget_parser.add_argument("selector")
    diff_parser = subparsers.add_parser("diff")
    diff_parser.add_argument("selector")
    args = parser.parse_args()
    root = pathlib.Path(args.root)
    if args.command == "list":
        items = list_artifacts(root)
        if args.json:
            print(json.dumps({"artifacts": items}, indent=2))
        else:
            print("Artifact Surfaces:")
            for item in items:
                print(f"- {item.get('trust_state')} {item.get('path')}")
        return 0
    if args.command == "trust":
        if set_trust(root, args.selector, "trusted"):
            print(f"trusted {args.selector}")
            return 0
        print(f"unknown artifact surface: {args.selector}", file=os.sys.stderr)
        return 1
    if args.command == "quarantine":
        if set_trust(root, args.selector, "quarantined"):
            print(f"quarantined {args.selector}")
            return 0
        print(f"unknown artifact surface: {args.selector}", file=os.sys.stderr)
        return 1
    if args.command == "forget":
        if forget_artifact(root, args.selector):
            print(f"forgot {args.selector}")
            return 0
        print(f"unknown artifact surface: {args.selector}", file=os.sys.stderr)
        return 1
    if args.command == "diff":
        payload = diff_artifact(root, args.selector)
        if payload is None:
            print(f"unknown artifact surface: {args.selector}", file=os.sys.stderr)
            return 1
        print(json.dumps(payload, indent=2))
        return 0
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
